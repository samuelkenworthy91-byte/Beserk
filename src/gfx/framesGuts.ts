// SCALE IS THE POINT. These numbers are set against the rest of the cast, not
// in isolation — "too big for ordinary soldiers" is a comparison, so it has to
// be drawn as one:
//
//                     figure height   weapon length   weapon width
//   levy soldier          46px            spear 2px shaft
//   raider                46px            axe head 12px
//   Bazuso (boss)         52px            axe head 16px
//   GUTS                  64px            blade 46px      blade 13px
//
// His blade is longer than an enemy soldier is tall and thicker than their
// torso. He is also the tallest figure in the game — taller than the boss.
// Anyone else holding this weapon would read as a mistake.
//
// Anatomy rules (as the rest of the cast): weight on one leg, shoulders and
// hips counter-rotate, near arm overlaps the chest, head angle changes per
// pose. Guts additionally gets:
//   BROAD        shoulder span ~34px against a levy's ~22px. He is the widest
//                silhouette in the game apart from Bazuso, and taller than him.
//   GROUNDED     feet never closer than 18px apart, both flat, knees bent.
//                He is always braced against the weight he is carrying.
//   FOLLOW-THRU  the blade keeps travelling after the hit lands; impact and
//                recover are separate ends of one continuous arc.

