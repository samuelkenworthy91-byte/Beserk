// ─── Hand-authored 96×96 dialogue portraits ──────────────────────────────────
// Bust illustrations, NOT enlarged sprites. Three principles separate these
// from the previous 64×64 set:
//
//   1. THREE-QUARTER VIEW. Faces turn slightly off-axis, so the near and far
//      halves differ in width, the far eye compresses, and the nose breaks the
//      cheek line. Asymmetry is structural rather than sprinkled on.
//   2. FIVE-STEP SKIN RAMPS. Enough tones to model a brow ridge, an eye socket,
//      a cheekbone and a jaw underplane. Four steps could only flatly fill.
//   3. LIT FORMS. A single key light from the upper left decides every tone;
//      shadow sides, core shadows and rim highlights are placed deliberately.
//
// Glyph legend — one char per pixel:
//   .  transparent
//   0  deepest shadow / interior line
//   1 2 3 4 5   skin:   deep shadow → shadow → mid → lit → highlight
//   6 7 8 9     hair:   darkest → dark → mid → highlight
//   a b c d e   armour: darkest → dark → mid → lit → rim
//   f g h       leather: dark → mid → lit
//   i j k       steel:  dark → mid → bright
//   m           gold trim
//   n o         accent cloth: dark / light
//   w v x       eye: white, iris, pupil
//   r           scar tissue
//   q           lip line
//   s           stubble / five-o-clock shadow
