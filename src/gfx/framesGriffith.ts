// ─── GRIFFITH — the White Hawk ───────────────────────────────────────────────
// 72×58 field, facing RIGHT, feet on row 57.
//
// ANATOMY NOTES
//   The whole figure is built for SPEED and GRACE, not mass. He is the only
//   cast member whose idle pose reads as a dancer's — lead foot pointed,
//   trailing cloak pulled by an off-screen wind, sword held low and ready.
//
//   SLIMNESS — waistline and shoulders are narrower than any infantry; only
//   Guts is taller. The cloak adds width but not mass — it reads as cloth
//   in motion, not bulk.
//
//   FACE — the lightest skin ramp in the cast, matching his portrait. White
//   hair (a/b/c glyphs, light end of the cool-grey ramp) frames a soft jaw
//   and downturned brow. The visor of authority, not the grin.
//
//   SWORD — a slender longsword, held point-down at rest. The blade is two
//   pixels wide and 28 pixels long. Compared with Guts' 46px slab it is a
//   rapier; compared with a levy sword it is a duellist's weapon.
//
//   CLOAK — runs from the shoulders down past the knees on both sides,
//   tapering. It pulls to the right (his back, away from the camera) so
//   every frame has a clear direction. On WIND it trails behind him. On
//   SWING it whips past the sword arc.

